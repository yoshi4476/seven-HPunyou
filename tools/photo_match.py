def _norm(s):
    """全角英数を半角に、英字は小文字に揃えてから照合する"""
    s = re.sub(r"<[^>]+>", " ", s or "")
    out = []
    for ch in s:
        o = ord(ch)
        out.append(chr(o - 0xFEE0) if 0xFF01 <= o <= 0xFF5E else ch)
    return "".join(out).lower()


def score(text, name):
    """1素材ぶんの一致度。キーワードの出現回数を数える(長い語ほど主題を表すため重み付け)

    neg に指定した語は減点する。「不採択」のように、肯定語(採択)を文字列として
    含みながら意味が反対になる語で誤選定が起きるのを防ぐ。
    """
    t = _norm(text)
    p = PHOTOS[name]
    total = 0
    for kw in p["kw"]:
        n = t.count(_norm(kw))
        if n:
            total += n * (2 if len(kw) >= 4 else 1)
    for kw in p.get("neg", []):
        total -= t.count(_norm(kw)) * 4
    return max(total, 0)


def pick(title="", desc="", heads=(), body="", exclude=(), candidates=None):
    """記事(またはセクション)に最も合う素材名を返す

    見出しとタイトルを厚く重み付けし、本文は補助的に使う。
    該当が無い場合は None を返す(呼び出し側で既定値を決める)。
    """
    weighted = " ".join([
        (title + " ") * 3,
        (desc + " ") * 2,
        (" ".join(heads) + " ") * 3,
        body,
    ])
    names = candidates if candidates is not None else list(PHOTOS)
    best, best_score = None, 0
    for name in names:
        if name in exclude:
            continue
        s = score(weighted, name)
        if s > best_score:
            best, best_score = name, s
    return best


def img_tag(name, for_body=True, lazy=True, extra_class=""):
    """<img> を組み立てる。width/height を必ず入れてCLSを防ぐ"""
    p = PHOTOS[name]
    w, h = p["size"] if for_body else p["thumb"]
    src = f"/assets/img/{name}.webp" if for_body else f"/assets/img/{name}-t.webp"
    cls = f' class="{extra_class}"' if extra_class else ""
    lz = ' loading="lazy" decoding="async"' if lazy else ""
    return (f'<img{cls} src="{src}" alt="{p["alt"]}" width="{w}" height="{h}"{lz}>')


def thumb_src(name):
    """カード用の (URL, width, height)"""
    w, h = PHOTOS[name]["thumb"]
    return f"/assets/img/{name}-t.webp", w, h
